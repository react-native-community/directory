export const SPM_AUTOGEN_MARKER = '// AUTO-GENERATED by scripts/generate-spm-autolinking.js';

export type SwiftPMPackageJson = { swiftpmConfig?: Record<string, unknown> } | null;

export type HasSwiftPMInput = {
  packageJson?: SwiftPMPackageJson;
  packageSwift?: string | null;
  iosPackageSwift?: string | null;
  reactNativeConfig?: string | null;
  isExpoModule?: boolean;
};

export default function hasSwiftPM({
  packageJson,
  packageSwift,
  iosPackageSwift,
  reactNativeConfig,
  isExpoModule,
}: HasSwiftPMInput): boolean {
  const swiftpmConfig = packageJson?.swiftpmConfig;
  const autolinkingPlugin = swiftpmConfig?.autolinkingPlugin;
  const hasConfig =
    typeof swiftpmConfig === 'object' &&
    swiftpmConfig !== null &&
    Object.keys(swiftpmConfig).length > 0;

  return (
    (typeof autolinkingPlugin === 'string' && autolinkingPlugin.length > 0) ||
    (typeof reactNativeConfig === 'string' &&
      /\bspm\s*:\s*\{[^}]{0,2000}\bautolinkingPlugin\s*:/.test(reactNativeConfig)) ||
    isUsableManifest(packageSwift, isExpoModule === true, hasConfig) ||
    isUsableManifest(iosPackageSwift, isExpoModule === true, hasConfig)
  );
}

function isUsableManifest(
  manifest: string | null | undefined,
  isExpoModule: boolean,
  hasConfig: boolean
) {
  if (
    typeof manifest !== 'string' ||
    manifest.length === 0 ||
    manifest.includes(SPM_AUTOGEN_MARKER)
  ) {
    return false;
  }

  const code = manifest.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\r\n]*/g, '');
  return (
    hasConfig ||
    (isExpoModule && /\.library\s*\(/.test(code)) ||
    /"React[A-Za-z0-9]*"|\bReactNative\b/.test(code)
  );
}
