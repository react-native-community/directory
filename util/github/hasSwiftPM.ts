export const SPM_AUTOGEN_MARKER = '// AUTO-GENERATED by scripts/generate-spm-autolinking.js';

const REACT_NATIVE_CONFIG_SPM_REGEX = /\bspm\s*:\s*\{[^}]{0,2000}\bautolinkingPlugin\s*:/;
const SWIFT_LIBRARY_REGEX = /\.library\s*\(/;
const REACT_DEPENDENCY_REGEX = /"React[A-Za-z0-9]*"|\bReactNative\b/;

export type SwiftPMConfig = Record<string, unknown>;

export type HasSwiftPMInput = {
  swiftPMConfig?: SwiftPMConfig;
  packageSwift?: string | null;
  iosPackageSwift?: string | null;
  reactNativeConfig?: string | null;
  isExpoModule?: boolean;
};

export default function hasSwiftPM({
  swiftPMConfig,
  packageSwift,
  iosPackageSwift,
  reactNativeConfig,
  isExpoModule,
}: HasSwiftPMInput): boolean {
  const autolinkingPlugin = swiftPMConfig?.autolinkingPlugin;
  const hasConfig =
    typeof swiftPMConfig === 'object' &&
    swiftPMConfig !== null &&
    Object.keys(swiftPMConfig).length > 0;

  return (
    (typeof autolinkingPlugin === 'string' && autolinkingPlugin.length > 0) ||
    (typeof reactNativeConfig === 'string' &&
      REACT_NATIVE_CONFIG_SPM_REGEX.test(reactNativeConfig)) ||
    isUsableManifest(packageSwift, !!isExpoModule, hasConfig) ||
    isUsableManifest(iosPackageSwift, !!isExpoModule, hasConfig)
  );
}

function isUsableManifest(
  manifest: string | null | undefined,
  isExpoModule: boolean,
  hasConfig: boolean
) {
  if (
    typeof manifest !== 'string' ||
    manifest.length === 0 ||
    manifest.includes(SPM_AUTOGEN_MARKER)
  ) {
    return false;
  }

  if (hasConfig) {
    return true;
  }

  const code = manifest.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\r\n]*/g, '');
  return (isExpoModule && SWIFT_LIBRARY_REGEX.test(code)) || REACT_DEPENDENCY_REGEX.test(code);
}
